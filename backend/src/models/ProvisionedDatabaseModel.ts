import mongoose, { Document, ObjectId, Schema } from "mongoose"
import { encryptedFields } from "../utils/encryptedFieldsPlugin"
import { SECRET_PLACEHOLDER } from "../utils/secretCrypto"

/** The name of a provisioned database, which its user takes too: lowercase, as safe in a URI as in a Kubernetes name */
export const PROVISIONED_DATABASE_NAME = /^[a-z0-9][a-z0-9_-]{0,62}$/

/** The resource a database feeds, in one of its environments */
export interface IProvisionedDatabaseLink {
    resourceId: ObjectId
    environmentId: ObjectId
}

/**
 * A database Flightroom created on a server of the project (MongoServer), with a user of its own
 * that reaches it and nothing else. Linked, it is what a resource connects to in one environment.
 */
export interface IProvisionedDatabase extends Document<ObjectId> {
    projectId: ObjectId
    serverId: ObjectId
    databaseName: string
    username: string
    /** Generated by the backend, encrypted at rest, never sent to a client */
    password: string
    link?: IProvisionedDatabaseLink | null
    /**
     * `cleanupRequired`: a create failed and the user Flightroom made for it could not be removed again, so it is
     * still on the server. Kept so that it is not forgotten: not linkable, removable with `user` (which tries the
     * drop again) or `record` only. Unset otherwise.
     */
    status?: "cleanupRequired"
    /** Why the user could not be removed, as the server said it, credentials blanked */
    cleanupReason?: string
    /** How far a removal got on the server: the data (of a drop), then the user. A retry skips what is done */
    removedFromServer?: "data" | "user"
    createdAt: Date
    updatedAt: Date
    toFrontendObject: () => Record<string, unknown>
}

const linkSchema = new Schema<IProvisionedDatabaseLink>(
    {
        resourceId: {
            type: Schema.Types.ObjectId,
            ref: "Resource",
            required: true
        },
        environmentId: {
            type: Schema.Types.ObjectId,
            ref: "Environment",
            required: true
        }
    },
    { _id: false }
)

const provisionedDatabaseSchema = new Schema<IProvisionedDatabase>(
    {
        projectId: {
            type: Schema.Types.ObjectId,
            ref: "Project",
            required: true,
            index: true
        },
        serverId: {
            type: Schema.Types.ObjectId,
            ref: "MongoServer",
            required: true
        },
        databaseName: {
            type: String,
            required: true,
            match: PROVISIONED_DATABASE_NAME
        },
        username: {
            type: String,
            required: true,
            match: PROVISIONED_DATABASE_NAME
        },
        password: {
            type: String,
            required: true
        },
        link: {
            type: linkSchema,
            required: false
        },
        status: {
            type: String,
            enum: ["cleanupRequired"],
            required: false
        },
        cleanupReason: {
            type: String,
            required: false
        },
        removedFromServer: {
            type: String,
            enum: ["data", "user"],
            required: false
        }
    },
    {
        timestamps: true
    }
)

provisionedDatabaseSchema.index({ serverId: 1, databaseName: 1 }, { unique: true })
// One database per environment of a resource: two would write the same variables
provisionedDatabaseSchema.index({ "link.resourceId": 1, "link.environmentId": 1 }, { unique: true, partialFilterExpression: { "link.resourceId": { $exists: true } } })

provisionedDatabaseSchema.plugin(encryptedFields, { model: "ProvisionedDatabase", paths: ["password"] })

/** The database as the console may see it: the password is only ever the placeholder */
provisionedDatabaseSchema.methods.toFrontendObject = function (): Record<string, unknown> {
    const object = this.toObject()
    delete object.__v
    object.password = SECRET_PLACEHOLDER
    return object
}

const ProvisionedDatabase = mongoose.model<IProvisionedDatabase>("ProvisionedDatabase", provisionedDatabaseSchema)
export default ProvisionedDatabase
